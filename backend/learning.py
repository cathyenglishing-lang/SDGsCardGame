def run_events(run_id: int, authorization: str | None = Header(default=None)):
    _teacher(authorization)
    conn, cur = get_db()
    cur.execute("SELECT * FROM learning_runs WHERE id = ?", (run_id,))
    run = cur.fetchone()
    if not run:
        conn.close()
        raise HTTPException(status_code=404, detail="run not found")
    cur.execute("SELECT seq, t_ms, stage, node, activity, type, detail, data_json, created_at FROM learning_events WHERE run_id = ? ORDER BY seq", (run_id,))
    evs = [dict(e) for e in cur.fetchall()]
    conn.close()
    for e in evs:
        e["data"] = _loads(e.pop("data_json"), None)
    if run["game"] == CARD_GAME:
        from backend import learning_reports
        summary = learning_reports.card_summary(dict(run), evs)
        flags = [(f, 1, f) for f in score_events(evs)["flags"]]
    else:
        summary = _summarize_run(dict(run), evs)
        flags, _ = _run_flags(dict(run), evs)
    run = dict(run)
    for k in ("vars_json", "stars_json", "metrics_json", "route_json"):
        run[k.replace("_json", "")] = _loads(run.pop(k), None)
    return {"run": run, "events": evs, "summary": summary, "flags": [{"code": c, "weight": w, "reason": m} for c, w, m in flags]}


@router.get("/export.xlsx")
def export_xlsx(authorization: str | None = Header(default=None), chapter: str | None = None, level: str | None = None,
                date_from: str | None = Query(default=None, alias="from"), date_to: str | None = Query(default=None, alias="to"),
                user: str | None = None):
    _teacher(authorization)
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Font, PatternFill
        from openpyxl.utils import get_column_letter
    except ImportError:
        raise HTTPException(status_code=500, detail="openpyxl is not installed")
    conn, cur = get_db()
    runs, events = _load_runs_and_events(cur, chapter, level, date_from, date_to, user)
    conn.close()
    agg = _aggregate(runs, events)

    wb = Workbook()
    head_font, head_fill = Font(bold=True, color="FFFFFF"), PatternFill("solid", fgColor="1F3A5F")

    def sheet(title, headers, rows):
        ws = wb.create_sheet(title) if wb.worksheets and wb.worksheets[0].title != "Sheet" else wb.active
        if ws.title == "Sheet":
            ws.title = title
        ws.append(headers)
        for c in ws[1]:
            c.font, c.fill = head_font, head_fill
        for r in rows:
            ws.append([excel_cell(v) for v in r])
        for i, h in enumerate(headers, 1):
            ws.column_dimensions[get_column_letter(i)].width = min(60, max(12, len(str(h)) + 4))
        ws.freeze_panes = "A2"
        return ws

    ov = agg["overview"]
    sheet("Summary", ["Metric", "Value"], [
        ["Exported", _now()], ["Filters", json.dumps(agg.get("filters") or {"chapter": chapter, "level": level, "from": date_from, "to": date_to, "user": user}, ensure_ascii=False)],
        ["Runs", ov["runs"]], ["Completed runs", ov["completed"]], ["Students", ov["students"]],
        ["Average stars", ov["avg_stars"]], ["Average minutes per completed run", ov["avg_minutes"]],
        ["Average speaking coverage %", ov["avg_coverage"]], ["Chinese hints per run", ov["hints_per_run"]],
    ] + [[f"Stage {s['stage'] + 1} {s['name']} avg stars", s["avg_stars"]] for s in agg["stages"]])
    sheet("Runs", ["run_id", "user_id", "username", "chapter", "level", "avatar", "started_at", "ended_at", "minutes", "ending", "avg_stars", "stars", "integrity", "evidence", "approach", "kai", "route", "events", "replays", "card_errors", "reading_sec", "zh_hints", "hits", "jumps", "overheard"],
          [[r["id"], r["user_id"], r["username"], r["chapter"], r["level"], r["avatar"], r["started_at"], r["ended_at"],
            round((datetime.fromisoformat(r["ended_at"]) - datetime.fromisoformat(r["started_at"])).total_seconds() / 60, 1) if r.get("ended_at") else None,
            r["ending"], (round(sum(_numeric_stars(st)) / len(_numeric_stars(st)), 2) if _numeric_stars(st) else None), st,
            v.get("integrity"), v.get("evidence"), v.get("approach"), v.get("kai"), " → ".join(_loads(r.get("route_json"), [])), r["event_count"],
            m.get("replays"), m.get("cardErrors"), m.get("readSec"), m.get("zhHints"), m.get("hits"), m.get("jumps"), m.get("eavesdrops")]
           for r in runs for st in [_loads(r.get("stars_json"), {})] for v in [_loads(r.get("vars_json"), {})] for m in [_loads(r.get("metrics_json"), {})]])
    sheet("Students", ["user_id", "username", "runs", "completed", "avg_stars", "best_ending", "levels", "missed_words_top3", "zh_hints", "last_played"],
          [[s["user_id"], s["username"], s["runs"], s["completed"], s["avg_stars"], s["best_ending"], ", ".join(s["levels"]), ", ".join(s["missed_top"]), s["hints"], s["last"]] for s in agg["students"]])
    sheet("Vocabulary", ["word", "misses (listening + reading + speaking)"], [[v["word"], v["misses"]] for v in agg["vocab"]])
    sheet("Endings", ["ending", "count"], [[e["ending"], e["count"]] for e in agg["endings"]])
    sheet("Choices", ["choice", "value", "count"], [[k, c["value"], c["count"]] for k, lst in agg["choices"].items() for c in lst])
    sheet("Routes", ["route", "count"], [[r["route"], r["count"]] for r in agg["routes"]])
    sheet("Anomalies", ["run_id", "username", "level", "started_at", "minutes", "ending", "score", "severity", "flags", "reasons"],
          [[a["run_id"], a["username"], a["level"], a["started_at"], a["minutes"], a["ending"], a["score"], a["severity"], ", ".join(a["flags"]), "；".join(a["reasons"])] for a in agg.get("anomalies", [])])
    sheet("StudentTexts", ["run_id", "username", "at", "kind", "ending", "text"], [[t["run_id"], t["username"], t["at"], t["kind"], t["ending"], t["text"]] for t in agg.get("texts", [])])
    ev_rows = []
    for r in runs:
        for e in events.get(r["id"], []):
            ev_rows.append([r["id"], r["username"], e["seq"], round((e["t_ms"] or 0) / 1000, 1), e["stage"], e["node"], e["type"], e["detail"], e.get("data")])
            if len(ev_rows) >= 50000:
                break
    sheet("Events", ["run_id", "username", "seq", "t_s", "stage", "node", "type", "detail", "data"], ev_rows)

    buf = io.BytesIO()
    wb.save(buf)
    name = f"innovation-harbor-learning-{datetime.now(TAIPEI).strftime('%Y%m%d-%H%M')}.xlsx"
    return Response(buf.getvalue(), media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                    headers={"Content-Disposition": f'attachment; filename="{name}"'})


