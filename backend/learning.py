# ── database ──
def _sql(sql: str):
    return re.sub(r"\?", "%s", sql) if USE_POSTGRES else sql


class _Cur:
    def __init__(self, cur):
        self.cur = cur

    def execute(self, sql, params=()):
        self.cur.execute(_sql(sql), params)
        return self

    def fetchone(self):
        return self.cur.fetchone()

    def fetchall(self):
        return self.cur.fetchall()


def get_db():
    if USE_POSTGRES:
        if psycopg is None:
            raise RuntimeError("LEARNING_DATABASE_URL is set, but psycopg is not installed")
        conn = psycopg.connect(DATABASE_URL, row_factory=dict_row)
        return conn, _Cur(conn.cursor())
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(DB_PATH, timeout=30)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA busy_timeout = 30000")
    try:
        conn.execute("PRAGMA journal_mode = WAL")
    except sqlite3.OperationalError:
        pass
    return conn, _Cur(conn.cursor())


def _pk():
    return "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if USE_POSTGRES else "INTEGER PRIMARY KEY AUTOINCREMENT"


def init_db():
    conn, cur = get_db()
    cur.execute(f"""
        CREATE TABLE IF NOT EXISTS learning_runs (
            id {_pk()},
            user_id INTEGER,
            username TEXT,
            game TEXT NOT NULL DEFAULT 'innovation-harbor',
            chapter TEXT NOT NULL DEFAULT '9-1',
            level TEXT,
            avatar TEXT,
            client TEXT,
            started_at TEXT NOT NULL,
            ended_at TEXT,
            ending TEXT,
            vars_json TEXT,
            stars_json TEXT,
            metrics_json TEXT,
            route_json TEXT,
            event_count INTEGER NOT NULL DEFAULT 0
        )""")
    cur.execute(f"""
        CREATE TABLE IF NOT EXISTS learning_events (
            id {_pk()},
            run_id INTEGER NOT NULL,
            seq INTEGER NOT NULL,
            t_ms INTEGER,
            stage TEXT,
            node TEXT,
            activity TEXT,
            type TEXT NOT NULL,
            detail TEXT,
            data_json TEXT,
            created_at TEXT NOT NULL,
            UNIQUE(run_id, seq)
        )""")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_learning_events_run ON learning_events(run_id)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_learning_events_type ON learning_events(type)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_learning_runs_user ON learning_runs(user_id)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_learning_runs_started ON learning_runs(started_at)")
    conn.commit()
    conn.close()


def _insert(cur, sql, params, id_col="id"):
    if USE_POSTGRES:
        cur.execute(f"{sql.strip()} RETURNING {id_col}", params)
        return cur.fetchone()[id_col]
    cur.execute(sql, params)
    return cur.cur.lastrowid


def _now():
    return datetime.now(TAIPEI).isoformat(timespec="seconds")


def _optional_user(authorization):
    if not authorization or not _auth["current"]:
        return None
    try:
        return _auth["current"](authorization)
    except HTTPException:
        return None


def _teacher(authorization):
    if not _auth["teacher"]:
        raise HTTPException(status_code=500, detail="learning module not configured")
    return _auth["teacher"](authorization)


