"""Learning analytics for the 3D story games (Innovation Harbor and later chapters).

Every learning event the game records (listening answers, speaking attempts, choices, route,
ending, safety incidents…) is stored here, in a database of its own:
  LEARNING_DATABASE_URL  PostgreSQL via psycopg (production)
  sql/learning.db        SQLite fallback (local / unset)
The main app only mounts the router; this module never touches the platform tables.

Student endpoints (token optional – anonymous runs are kept with the username the game sends):
  POST /learning/runs                 start a run → {run_id}
  POST /learning/events               batch of events (idempotent on run_id + seq)
  POST /learning/runs/{id}/finish     ending, variables, stars, metrics, route
Teacher endpoints (teacher/admin token):
  GET  /learning/analytics            aggregated dashboard data (filters: chapter, level, from, to, user)
  GET  /learning/runs                 run list;  GET /learning/runs/{id}/events  one run's events
  GET  /learning/export.xlsx          Excel workbook (Summary, Runs, Students, Vocabulary, Endings, Choices, Events)
"""
from __future__ import annotations

import io
import json
import os
import re
import sqlite3
from collections import Counter, defaultdict
from datetime import datetime, timedelta, timezone
from pathlib import Path

from fastapi import APIRouter, Header, HTTPException, Query, Response
from pydantic import BaseModel

try:
    import psycopg
    from psycopg.rows import dict_row
except ImportError:  # pragma: no cover
    psycopg = None
    dict_row = None

router = APIRouter(prefix="/learning", tags=["learning"])

BASE_DIR = Path(__file__).resolve().parent.parent
DB_PATH = BASE_DIR / "sql" / "learning.db"
DATABASE_URL = os.getenv("LEARNING_DATABASE_URL", "").strip()
USE_POSTGRES = bool(DATABASE_URL)
TAIPEI = timezone(timedelta(hours=8))
STAGE_NAMES = ["Hook", "Problem", "Explain", "Impact", "Strategy", "Conclusion"]
MAX_BATCH = 200

_auth = {"current": None, "teacher": None}


def configure(get_current_user, require_teacher):
    """Wire the platform's JWT helpers in (keeps this module free of main.py imports)."""
    _auth["current"] = get_current_user
    _auth["teacher"] = require_teacher


# ── database ──
def _sql(sql: str):
    return re.sub(r"\?", "%s", sql) if USE_POSTGRES else sql


class _Cur:
    def __init__(self, cur):
        self.cur = cur

    def execute(self, sql, params=()):
        self.cur.execute(_sql(sql), params)
        return self

    def fetchone(self):
        return self.cur.fetchone()

    def fetchall(self):
        return self.cur.fetchall()


def get_db():
    if USE_POSTGRES:
        if psycopg is None:
            raise RuntimeError("LEARNING_DATABASE_URL is set, but psycopg is not installed")
        conn = psycopg.connect(DATABASE_URL, row_factory=dict_row)
        return conn, _Cur(conn.cursor())
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(DB_PATH, timeout=30)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA busy_timeout = 30000")
    try:
        conn.execute("PRAGMA journal_mode = WAL")
    except sqlite3.OperationalError:
        pass
    return conn, _Cur(conn.cursor())


def _pk():
    return "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if USE_POSTGRES else "INTEGER PRIMARY KEY AUTOINCREMENT"


def init_db():
    conn, cur = get_db()
    cur.execute(f"""
        CREATE TABLE IF NOT EXISTS learning_runs (
            id {_pk()},
            user_id INTEGER,
            username TEXT,
            game TEXT NOT NULL DEFAULT 'innovation-harbor',
            chapter TEXT NOT NULL DEFAULT '9-1',
            level TEXT,
            avatar TEXT,
            client TEXT,
            started_at TEXT NOT NULL,
            ended_at TEXT,
            ending TEXT,
            vars_json TEXT,
            stars_json TEXT,
            metrics_json TEXT,
            route_json TEXT,
            event_count INTEGER NOT NULL DEFAULT 0
        )""")
    cur.execute(f"""
        CREATE TABLE IF NOT EXISTS learning_events (
            id {_pk()},
            run_id INTEGER NOT NULL,
            seq INTEGER NOT NULL,
            t_ms INTEGER,
            stage TEXT,
            node TEXT,
            activity TEXT,
            type TEXT NOT NULL,
            detail TEXT,
            data_json TEXT,
            created_at TEXT NOT NULL,
            UNIQUE(run_id, seq)
        )""")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_learning_events_run ON learning_events(run_id)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_learning_events_type ON learning_events(type)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_learning_runs_user ON learning_runs(user_id)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_learning_runs_started ON learning_runs(started_at)")
    conn.commit()
    conn.close()


def _insert(cur, sql, params, id_col="id"):
    if USE_POSTGRES:
        cur.execute(f"{sql.strip()} RETURNING {id_col}", params)
        return cur.fetchone()[id_col]
    cur.execute(sql, params)
    return cur.cur.lastrowid


def _now():
    return datetime.now(TAIPEI).isoformat(timespec="seconds")


def _optional_user(authorization):
    if not authorization or not _auth["current"]:
        return None
    try:
        return _auth["current"](authorization)
    except HTTPException:
        return None


def _teacher(authorization):
    if not _auth["teacher"]:
        raise HTTPException(status_code=500, detail="learning module not configured")
    return _auth["teacher"](authorization)


# ── schemas ──
class RunStartIn(BaseModel):
    game: str = "innovation-harbor"
    chapter: str = "9-1"
    level: str = "A2"
    avatar: str | None = None
    username: str | None = None
    client: str | None = None


class EventIn(BaseModel):
    seq: int
    t: float | None = None          # seconds since run start
    stage: str | int | None = None
    node: str | None = None
    activity: str | None = None
    type: str
    detail: str | None = None
    data: dict | None = None


class EventsIn(BaseModel):
    run_id: int
    events: list[EventIn]


class RunFinishIn(BaseModel):
    ending: str | None = None
    vars: dict | None = None
    stars: dict | None = None
    metrics: dict | None = None
    route: list | None = None


# ── student endpoints ──
@router.post("/runs")
def start_run(data: RunStartIn, authorization: str | None = Header(default=None)):
    user = _optional_user(authorization)
    conn, cur = get_db()
    run_id = _insert(cur, """
        INSERT INTO learning_runs (user_id, username, game, chapter, level, avatar, client, started_at)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
        (user["id"] if user else None,
         (user.get("name") if user else None) or (data.username or "anonymous")[:80],
         data.game[:40], data.chapter[:20], data.level[:8], (data.avatar or "")[:20], (data.client or "")[:200], _now()))
    conn.commit()
    conn.close()
    return {"run_id": run_id}


def _own_run(cur, run_id, user):
    cur.execute("SELECT id, user_id, ended_at FROM learning_runs WHERE id = ?", (run_id,))
    run = cur.fetchone()
    if not run:
        raise HTTPException(status_code=404, detail="run not found")
    if run["user_id"] is not None and user and run["user_id"] != user["id"]:
        raise HTTPException(status_code=403, detail="not your run")
    return run


@router.post("/events")
def post_events(data: EventsIn, authorization: str | None = Header(default=None)):
    if len(data.events) > MAX_BATCH:
        raise HTTPException(status_code=400, detail=f"at most {MAX_BATCH} events per batch")
    user = _optional_user(authorization)
    conn, cur = get_db()
    _own_run(cur, data.run_id, user)
    stored = 0
    for e in data.events:
        payload = json.dumps(e.data, ensure_ascii=False)[:4000] if e.data else None
        try:
            cur.execute("""
                INSERT INTO learning_events (run_id, seq, t_ms, stage, node, activity, type, detail, data_json, created_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                (data.run_id, e.seq, int((e.t or 0) * 1000), str(e.stage) if e.stage is not None else None,
                 (e.node or None), (e.activity or None), e.type[:40], (e.detail or "")[:500], payload, _now()))
            stored += 1
        except Exception as err:  # duplicate seq → already stored (client retried)
            if "UNIQUE" in str(err).upper() or "duplicate" in str(err).lower():
                if USE_POSTGRES:
                    conn.rollback()
                continue
            raise
    cur.execute("UPDATE learning_runs SET event_count = event_count + ? WHERE id = ?", (stored, data.run_id))
    conn.commit()
    conn.close()
    return {"stored": stored}


@router.post("/runs/{run_id}/finish")
def finish_run(run_id: int, data: RunFinishIn, authorization: str | None = Header(default=None)):
    user = _optional_user(authorization)
    conn, cur = get_db()
    _own_run(cur, run_id, user)
    cur.execute("""
        UPDATE learning_runs SET ended_at = ?, ending = ?, vars_json = ?, stars_json = ?, metrics_json = ?, route_json = ?
        WHERE id = ?""",
        (_now(), (data.ending or "")[:40], json.dumps(data.vars or {}, ensure_ascii=False)[:4000],
         json.dumps(data.stars or {})[:1000], json.dumps(data.metrics or {}, ensure_ascii=False)[:4000],
         json.dumps(data.route or [])[:2000], run_id))
    conn.commit()
    conn.close()
    return {"message": "run finished"}


# ── aggregation ──
def _loads(s, default):
    try:
        return json.loads(s) if s else default
    except Exception:
        return default


def _numeric_stars(stars: dict):
    return [v for v in stars.values() if isinstance(v, (int, float))]


def _filters(chapter, level, date_from, date_to, user):
    where, params = [], []
    if chapter:
        where.append("r.chapter = ?"); params.append(chapter)
    if level:
        where.append("r.level = ?"); params.append(level)
    if date_from:
        where.append("r.started_at >= ?"); params.append(date_from)
    if date_to:
        where.append("r.started_at <= ?"); params.append(date_to + "T23:59:59")
    if user:
        where.append("(r.username LIKE ? OR CAST(r.user_id AS TEXT) = ?)"); params.extend([f"%{user}%", user])
    return (" WHERE " + " AND ".join(where)) if where else "", params


def _load_runs_and_events(cur, chapter, level, date_from, date_to, user):
    where, params = _filters(chapter, level, date_from, date_to, user)
    cur.execute(f"SELECT r.* FROM learning_runs r{where} ORDER BY r.started_at DESC", params)
    runs = [dict(r) for r in cur.fetchall()]
    events = defaultdict(list)
    ids = [r["id"] for r in runs]
    for i in range(0, len(ids), 400):
        chunk = ids[i:i + 400]
        ph = ",".join("?" for _ in chunk)
        cur.execute(f"SELECT run_id, seq, t_ms, stage, node, type, detail, data_json FROM learning_events WHERE run_id IN ({ph}) ORDER BY run_id, seq", tuple(chunk))
        for e in cur.fetchall():
            d = dict(e); d["data"] = _loads(d.pop("data_json"), None); events[d["run_id"]].append(d)
    return runs, events


def _aggregate(runs, events):
    avg = lambda xs: round(sum(xs) / len(xs), 2) if xs else 0
    endings, choices, nodes_done, node_retry = Counter(), defaultdict(Counter), Counter(), Counter()
    stage_stars, stage_pending, stage_skip = defaultdict(list), Counter(), Counter()
    missed, listen_wrong, replays, coverages, hints, routes = Counter(), Counter(), [], [], [], Counter()
    speech_modes, safety, per_day, durations = Counter(), Counter(), Counter(), []
    students = {}
    for r in runs:
        evs = events.get(r["id"], [])
        stars = _loads(r.get("stars_json"), {}); vars_ = _loads(r.get("vars_json"), {}); metrics = _loads(r.get("metrics_json"), {})
        if r.get("ending"):
            endings[r["ending"]] += 1
        per_day[str(r["started_at"])[:10]] += 1
        if r.get("ended_at"):
            try:
                durations.append((datetime.fromisoformat(r["ended_at"]) - datetime.fromisoformat(r["started_at"])).total_seconds())
            except Exception:
                pass
        for k, v in stars.items():
            if isinstance(v, (int, float)) and str(k).isdigit():
                stage_stars[int(k)].append(v)
            elif v == "pending":
                stage_pending[k] += 1
            elif v == "skip":
                stage_skip[k] += 1
        route = _loads(r.get("route_json"), [])
        if route:
            routes[" → ".join(route)] += 1
        plays = 0
        for e in evs:
            t, d = e["type"], e.get("data") or {}
            if t == "story.choice" and d.get("key"):
                choices[d["key"]][str(d.get("value"))] += 1
            elif t == "node.done":
                nodes_done[d.get("node") or e.get("node") or "?"] += 1
                if d.get("outcome") == "retry":
                    node_retry[d.get("node") or "?"] += 1
            elif t == "listen.play":
                plays += 1
            elif t == "listen.answer":
                if d.get("wrong"):
                    listen_wrong[d.get("word", "?")] += 1
                    missed[d.get("word", "?")] += 1
            elif t in ("speak.attempt", "pk.slide"):
                if d.get("coverage") is not None:
                    coverages.append(float(d["coverage"]))
                for w in d.get("missed") or []:
                    missed[w] += 1
            elif t == "read.find" and d.get("wrong"):
                missed[d.get("word", "?")] += 1
            elif t == "hint.zh":
                hints.append(1)
            elif t == "speak.record" or t == "pk.record":
                speech_modes["recorded for teacher"] += 1
            elif t in ("speak.skip", "pk.skip"):
                speech_modes["skipped (no microphone)"] += 1
            elif t == "safety.hit":
                safety["hit by traffic"] += 1
            elif t == "drive.enter":
                safety["drives"] += 1
            elif t == "story.overhear":
                safety["overheard hints"] += 1
            elif t == "portal.touch":
                safety["touched locked bridge"] += 1
        replays.append(max(0, plays - 2))  # two slides play once each; the rest are replays
        key = r.get("user_id") or f"name:{r.get('username')}"
        s = students.setdefault(key, {"user_id": r.get("user_id"), "username": r.get("username"), "runs": 0, "completed": 0, "stars": [], "endings": Counter(), "missed": Counter(), "hints": 0, "last": r["started_at"], "levels": set()})
        s["runs"] += 1; s["completed"] += 1 if r.get("ended_at") else 0
        s["stars"].extend(_numeric_stars(stars)); s["levels"].add(r.get("level") or "")
        if r.get("ending"):
            s["endings"][r["ending"]] += 1
        s["hints"] += metrics.get("zhHints", 0) if isinstance(metrics, dict) else 0
        for w in metrics.get("missed", []) if isinstance(metrics, dict) else []:
            s["missed"][w] += 1
        s["last"] = max(s["last"], r["started_at"])
    all_stars = [v for lst in stage_stars.values() for v in lst]
    student_rows = sorted([{
        "user_id": s["user_id"], "username": s["username"], "runs": s["runs"], "completed": s["completed"],
        "avg_stars": avg(s["stars"]), "best_ending": (s["endings"].most_common(1) or [("", 0)])[0][0],
        "missed_top": [w for w, _ in s["missed"].most_common(3)], "hints": s["hints"], "last": s["last"],
        "levels": sorted(l for l in s["levels"] if l),
    } for s in students.values()], key=lambda x: x["last"], reverse=True)
    return {
        "overview": {
            "runs": len(runs), "completed": sum(1 for r in runs if r.get("ended_at")), "students": len(students),
            "avg_stars": avg(all_stars), "avg_minutes": round(avg(durations) / 60, 1) if durations else 0,
            "avg_coverage": round(avg(coverages) * 100) if coverages else None, "hints_per_run": avg(hints) if runs else 0,
        },
        "endings": [{"ending": k, "count": v} for k, v in endings.most_common()],
        "stages": [{"stage": i, "name": STAGE_NAMES[i], "avg_stars": avg(stage_stars.get(i, [])), "n": len(stage_stars.get(i, [])),
                    "pending": stage_pending.get(str(i), 0), "skipped": stage_skip.get(str(i), 0)} for i in range(6)],
        "vocab": [{"word": w, "misses": c} for w, c in missed.most_common(20)],
        "listening_words": [{"word": w, "wrong": c} for w, c in listen_wrong.most_common(10)],
        "replays": {"avg": avg(replays), "histogram": [{"replays": k, "runs": v} for k, v in sorted(Counter(min(r, 6) for r in replays).items())]},
        "choices": {k: [{"value": a, "count": b} for a, b in v.most_common()] for k, v in choices.items()},
        "nodes": [{"node": k, "done": v, "retries": node_retry.get(k, 0)} for k, v in nodes_done.most_common()],
        "routes": [{"route": k, "count": v} for k, v in routes.most_common(8)],
        "speech": {"modes": [{"mode": k, "count": v} for k, v in speech_modes.items()], "coverage_avg": round(avg(coverages) * 100) if coverages else None},
        "explore": [{"kind": k, "count": v} for k, v in safety.most_common()],
        "timeline": [{"day": k, "runs": v} for k, v in sorted(per_day.items())][-30:],
        "students": student_rows,
    }


# ── teacher endpoints ──
@router.get("/analytics")
def analytics(authorization: str | None = Header(default=None), chapter: str | None = None, level: str | None = None,
              date_from: str | None = Query(default=None, alias="from"), date_to: str | None = Query(default=None, alias="to"),
              user: str | None = None):
    _teacher(authorization)
    conn, cur = get_db()
    runs, events = _load_runs_and_events(cur, chapter, level, date_from, date_to, user)
    conn.close()
    out = _aggregate(runs, events)
    out["filters"] = {"chapter": chapter, "level": level, "from": date_from, "to": date_to, "user": user}
    out["recent"] = [{"id": r["id"], "username": r["username"], "chapter": r["chapter"], "level": r["level"], "started_at": r["started_at"],
                      "ended_at": r["ended_at"], "ending": r["ending"], "events": r["event_count"],
                      "avg_stars": round(sum(_numeric_stars(_loads(r.get("stars_json"), {}))) / max(1, len(_numeric_stars(_loads(r.get("stars_json"), {})))), 1) if _numeric_stars(_loads(r.get("stars_json"), {})) else None}
                     for r in runs[:40]]
    return out


@router.get("/runs")
def list_runs(authorization: str | None = Header(default=None), chapter: str | None = None, level: str | None = None,
              date_from: str | None = Query(default=None, alias="from"), date_to: str | None = Query(default=None, alias="to"),
              user: str | None = None, limit: int = 200):
    _teacher(authorization)
    conn, cur = get_db()
    where, params = _filters(chapter, level, date_from, date_to, user)
    cur.execute(f"SELECT r.* FROM learning_runs r{where} ORDER BY r.started_at DESC LIMIT ?", params + [max(1, min(limit, 1000))])
    rows = [dict(r) for r in cur.fetchall()]
    conn.close()
    for r in rows:
        for k in ("vars_json", "stars_json", "metrics_json", "route_json"):
            r[k.replace("_json", "")] = _loads(r.pop(k), None)
    return {"runs": rows}


@router.get("/runs/{run_id}/events")
def run_events(run_id: int, authorization: str | None = Header(default=None)):
    _teacher(authorization)
    conn, cur = get_db()
    cur.execute("SELECT * FROM learning_runs WHERE id = ?", (run_id,))
    run = cur.fetchone()
    if not run:
        conn.close()
        raise HTTPException(status_code=404, detail="run not found")
    cur.execute("SELECT seq, t_ms, stage, node, activity, type, detail, data_json, created_at FROM learning_events WHERE run_id = ? ORDER BY seq", (run_id,))
    evs = [dict(e) for e in cur.fetchall()]
    conn.close()
    for e in evs:
        e["data"] = _loads(e.pop("data_json"), None)
    run = dict(run)
    for k in ("vars_json", "stars_json", "metrics_json", "route_json"):
        run[k.replace("_json", "")] = _loads(run.pop(k), None)
    return {"run": run, "events": evs}


@router.get("/export.xlsx")
def export_xlsx(authorization: str | None = Header(default=None), chapter: str | None = None, level: str | None = None,
                date_from: str | None = Query(default=None, alias="from"), date_to: str | None = Query(default=None, alias="to"),
                user: str | None = None):
    _teacher(authorization)
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Font, PatternFill
        from openpyxl.utils import get_column_letter
    except ImportError:
        raise HTTPException(status_code=500, detail="openpyxl is not installed")
    conn, cur = get_db()
    runs, events = _load_runs_and_events(cur, chapter, level, date_from, date_to, user)
    conn.close()
    agg = _aggregate(runs, events)

    wb = Workbook()
    head_font, head_fill = Font(bold=True, color="FFFFFF"), PatternFill("solid", fgColor="1F3A5F")

    def sheet(title, headers, rows):
        ws = wb.create_sheet(title) if wb.worksheets and wb.worksheets[0].title != "Sheet" else wb.active
        if ws.title == "Sheet":
            ws.title = title
        ws.append(headers)
        for c in ws[1]:
            c.font, c.fill = head_font, head_fill
        for r in rows:
            ws.append([("" if v is None else (json.dumps(v, ensure_ascii=False) if isinstance(v, (dict, list)) else v)) for v in r])
        for i, h in enumerate(headers, 1):
            ws.column_dimensions[get_column_letter(i)].width = min(60, max(12, len(str(h)) + 4))
        ws.freeze_panes = "A2"
        return ws

    ov = agg["overview"]
    sheet("Summary", ["Metric", "Value"], [
        ["Exported", _now()], ["Filters", json.dumps(agg.get("filters") or {"chapter": chapter, "level": level, "from": date_from, "to": date_to, "user": user}, ensure_ascii=False)],
        ["Runs", ov["runs"]], ["Completed runs", ov["completed"]], ["Students", ov["students"]],
        ["Average stars", ov["avg_stars"]], ["Average minutes per completed run", ov["avg_minutes"]],
        ["Average speaking coverage %", ov["avg_coverage"]], ["Chinese hints per run", ov["hints_per_run"]],
    ] + [[f"Stage {s['stage'] + 1} {s['name']} avg stars", s["avg_stars"]] for s in agg["stages"]])
    sheet("Runs", ["run_id", "user_id", "username", "chapter", "level", "avatar", "started_at", "ended_at", "minutes", "ending", "avg_stars", "stars", "integrity", "evidence", "approach", "kai", "route", "events", "replays", "card_errors", "reading_sec", "zh_hints", "hits", "jumps", "overheard"],
          [[r["id"], r["user_id"], r["username"], r["chapter"], r["level"], r["avatar"], r["started_at"], r["ended_at"],
            round((datetime.fromisoformat(r["ended_at"]) - datetime.fromisoformat(r["started_at"])).total_seconds() / 60, 1) if r.get("ended_at") else None,
            r["ending"], (round(sum(_numeric_stars(st)) / len(_numeric_stars(st)), 2) if _numeric_stars(st) else None), st,
            v.get("integrity"), v.get("evidence"), v.get("approach"), v.get("kai"), " → ".join(_loads(r.get("route_json"), [])), r["event_count"],
            m.get("replays"), m.get("cardErrors"), m.get("readSec"), m.get("zhHints"), m.get("hits"), m.get("jumps"), m.get("eavesdrops")]
           for r in runs for st in [_loads(r.get("stars_json"), {})] for v in [_loads(r.get("vars_json"), {})] for m in [_loads(r.get("metrics_json"), {})]])
    sheet("Students", ["user_id", "username", "runs", "completed", "avg_stars", "best_ending", "levels", "missed_words_top3", "zh_hints", "last_played"],
          [[s["user_id"], s["username"], s["runs"], s["completed"], s["avg_stars"], s["best_ending"], ", ".join(s["levels"]), ", ".join(s["missed_top"]), s["hints"], s["last"]] for s in agg["students"]])
