"""Learning analytics for the 3D story games (Innovation Harbor and later chapters).

Every learning event the game records (listening answers, speaking attempts, choices, route,
ending, safety incidents…) is stored here, in a database of its own:
  LEARNING_DATABASE_URL  PostgreSQL via psycopg (production)
  sql/learning.db        SQLite fallback (local / unset)
The main app only mounts the router; this module never touches the platform tables.

Student endpoints (token optional – anonymous runs are kept with the username the game sends):
  POST /learning/runs                 start a run → {run_id}
  POST /learning/events               batch of events (idempotent on run_id + seq)
  POST /learning/runs/{id}/finish     ending, variables, stars, metrics, route
Teacher endpoints (teacher/admin token):
  GET  /learning/analytics            aggregated dashboard data (filters: chapter, level, from, to, user)
  GET  /learning/runs                 run list;  GET /learning/runs/{id}/events  one run's events
  GET  /learning/export.xlsx          Excel workbook (Summary, Runs, Students, Vocabulary, Endings, Choices, Events)
"""
