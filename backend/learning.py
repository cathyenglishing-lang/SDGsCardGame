    if r.get("ending"): s.append(f"結局：{ENDING_ZH.get(r['ending'], r['ending'])}，證據 {vars_.get('evidence', '?')}、誠信 {vars_.get('integrity', '?')}，平均 {sum(nums)/len(nums):.1f} 星。" if nums else f"結局：{ENDING_ZH.get(r['ending'], r['ending'])}。")
