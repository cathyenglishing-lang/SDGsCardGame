def _loads(s, default):
    try:
        return json.loads(s) if s else default
    except Exception:
        return default


def _numeric_stars(stars: dict):
    return [v for v in stars.values() if isinstance(v, (int, float))]


def _filters(chapter, level, date_from, date_to, user, game=None):
    # game=None: the 3D story games (every run that is not the card game, which has its own report)
    where, params = (["r.game = ?"], [game]) if game else (["r.game <> ?"], [CARD_GAME])
    if chapter:
        where.append("r.chapter = ?"); params.append(chapter)
    if level:
        where.append("r.level = ?"); params.append(level)
    if date_from:
        where.append("r.started_at >= ?"); params.append(date_from)
    if date_to:
        where.append("r.started_at <= ?"); params.append(date_to + "T23:59:59")
    if user:
        where.append("(r.username LIKE ? OR CAST(r.user_id AS TEXT) = ?)"); params.extend([f"%{user}%", user])
    return (" WHERE " + " AND ".join(where)) if where else "", params


def _load_runs_and_events(cur, chapter, level, date_from, date_to, user):
    where, params = _filters(chapter, level, date_from, date_to, user)
    cur.execute(f"SELECT r.* FROM learning_runs r{where} ORDER BY r.started_at DESC", params)
    runs = [dict(r) for r in cur.fetchall()]
    events = defaultdict(list)
    ids = [r["id"] for r in runs]
    for i in range(0, len(ids), 400):
        chunk = ids[i:i + 400]
        ph = ",".join("?" for _ in chunk)
        cur.execute(f"SELECT run_id, seq, t_ms, stage, node, type, detail, data_json FROM learning_events WHERE run_id IN ({ph}) ORDER BY run_id, seq", tuple(chunk))
        for e in cur.fetchall():
            d = dict(e); d["data"] = _loads(d.pop("data_json"), None); events[d["run_id"]].append(d)
    return runs, events


def _aggregate(runs, events):
    avg = lambda xs: round(sum(xs) / len(xs), 2) if xs else 0
    endings, choices, nodes_done, node_retry = Counter(), defaultdict(Counter), Counter(), Counter()
    stage_stars, stage_pending, stage_skip = defaultdict(list), Counter(), Counter()
    missed, listen_wrong, replays, coverages, hints, routes = Counter(), Counter(), [], [], [], Counter()
    speech_modes, safety, per_day, durations = Counter(), Counter(), Counter(), []
    students = {}
    for r in runs:
        evs = events.get(r["id"], [])
        stars = _loads(r.get("stars_json"), {}); vars_ = _loads(r.get("vars_json"), {}); metrics = _loads(r.get("metrics_json"), {})
        if r.get("ending"):
            endings[r["ending"]] += 1
        per_day[str(r["started_at"])[:10]] += 1
        if r.get("ended_at"):
            try:
                durations.append((datetime.fromisoformat(r["ended_at"]) - datetime.fromisoformat(r["started_at"])).total_seconds())
            except Exception:
                pass
        for k, v in stars.items():
            if isinstance(v, (int, float)) and str(k).isdigit():
                stage_stars[int(k)].append(v)
            elif v == "pending":
                stage_pending[k] += 1
            elif v == "skip":
                stage_skip[k] += 1
        route = _loads(r.get("route_json"), [])
        if route:
            routes[" → ".join(route)] += 1
        plays = 0
        for e in evs:
            t, d = e["type"], e.get("data") or {}
            if t == "story.choice" and d.get("key"):
                choices[d["key"]][str(d.get("value"))] += 1
            elif t == "node.done":
                nodes_done[d.get("node") or e.get("node") or "?"] += 1
                if d.get("outcome") == "retry":
                    node_retry[d.get("node") or "?"] += 1
            elif t == "listen.play":
                plays += 1
            elif t == "listen.answer":
                if d.get("wrong"):
                    listen_wrong[d.get("word", "?")] += 1
                    missed[d.get("word", "?")] += 1
            elif t in ("speak.attempt", "pk.slide"):
                if d.get("coverage") is not None:
                    coverages.append(float(d["coverage"]))
                for w in d.get("missed") or []:
                    missed[w] += 1
            elif t == "read.find" and d.get("wrong"):
                missed[d.get("word", "?")] += 1
            elif t == "hint.zh":
                hints.append(1)
            elif t == "speak.record" or t == "pk.record":
                speech_modes["recorded for teacher"] += 1
            elif t in ("speak.skip", "pk.skip"):
                speech_modes["skipped (no microphone)"] += 1
            elif t == "safety.hit":
                safety["hit by traffic"] += 1
            elif t == "drive.enter":
                safety["drives"] += 1
            elif t == "story.overhear":
                safety["overheard hints"] += 1
            elif t == "portal.touch":
                safety["touched locked bridge"] += 1
        replays.append(max(0, plays - 2))  # two slides play once each; the rest are replays
        key = r.get("user_id") or f"name:{r.get('username')}"
        s = students.setdefault(key, {"user_id": r.get("user_id"), "username": r.get("username"), "runs": 0, "completed": 0, "stars": [], "endings": Counter(), "missed": Counter(), "hints": 0, "last": r["started_at"], "levels": set()})
        s["runs"] += 1; s["completed"] += 1 if r.get("ended_at") else 0
        s["stars"].extend(_numeric_stars(stars)); s["levels"].add(r.get("level") or "")
        if r.get("ending"):
            s["endings"][r["ending"]] += 1
        s["hints"] += metrics.get("zhHints", 0) if isinstance(metrics, dict) else 0
        for w in metrics.get("missed", []) if isinstance(metrics, dict) else []:
            s["missed"][w] += 1
        s["last"] = max(s["last"], r["started_at"])
    all_stars = [v for lst in stage_stars.values() for v in lst]
    student_rows = sorted([{
        "user_id": s["user_id"], "username": s["username"], "runs": s["runs"], "completed": s["completed"],
        "avg_stars": avg(s["stars"]), "best_ending": (s["endings"].most_common(1) or [("", 0)])[0][0],
        "missed_top": [w for w, _ in s["missed"].most_common(3)], "hints": s["hints"], "last": s["last"],
        "levels": sorted(l for l in s["levels"] if l),
    } for s in students.values()], key=lambda x: x["last"], reverse=True)
    return {
        "overview": {
            "runs": len(runs), "completed": sum(1 for r in runs if r.get("ended_at")), "students": len(students),
            "avg_stars": avg(all_stars), "avg_minutes": round(avg(durations) / 60, 1) if durations else 0,
            "avg_coverage": round(avg(coverages) * 100) if coverages else None, "hints_per_run": avg(hints) if runs else 0,
        },
        "endings": [{"ending": k, "count": v} for k, v in endings.most_common()],
        "stages": [{"stage": i, "name": STAGE_NAMES[i], "avg_stars": avg(stage_stars.get(i, [])), "n": len(stage_stars.get(i, [])),
                    "pending": stage_pending.get(str(i), 0), "skipped": stage_skip.get(str(i), 0)} for i in range(6)],
        "vocab": [{"word": w, "misses": c} for w, c in missed.most_common(20)],
        "listening_words": [{"word": w, "wrong": c} for w, c in listen_wrong.most_common(10)],
        "replays": {"avg": avg(replays), "histogram": [{"replays": k, "runs": v} for k, v in sorted(Counter(min(r, 6) for r in replays).items())]},
        "choices": {k: [{"value": a, "count": b} for a, b in v.most_common()] for k, v in choices.items()},
        "nodes": [{"node": k, "done": v, "retries": node_retry.get(k, 0)} for k, v in nodes_done.most_common()],
        "routes": [{"route": k, "count": v} for k, v in routes.most_common(8)],
        "speech": {"modes": [{"mode": k, "count": v} for k, v in speech_modes.items()], "coverage_avg": round(avg(coverages) * 100) if coverages else None},
        "explore": [{"kind": k, "count": v} for k, v in safety.most_common()],
        "timeline": [{"day": k, "runs": v} for k, v in sorted(per_day.items())][-30:],
        "students": student_rows,
        "anomalies": _anomalies(runs, events),
        "texts": _texts(runs, events)[:100],
    }



